    def list_paginated(self, origin: Optional[str] = None,
                       tone: Optional[str] = None,
                       person: Optional[str] = None,
                       tag: Optional[str] = None,
                       sort: str = "recent",
                       q: Optional[str] = None,
                       limit: int = 20,
                       offset: int = 0) -> Dict:
        """
        Return ``{items: [ExperientialMemory, ...], total: int}`` with
        optional filters and pagination.

        If *q* is provided, text search is performed via SQL LIKE.
        Otherwise a full scan with filters is used.
        """
        import sqlite3 as _sqlite3

        conditions: list = []
        params: list = []

        # -- Text search --
        if q:
            words = q.lower().split()
            if words:
                clauses = ["LOWER(content) LIKE ?" for _ in words]
                conditions.append("(" + " OR ".join(clauses) + ")")
                params.extend(f"%{w}%" for w in words)

        # -- Filters --
        if origin:
            conditions.append("origin = ?")
            params.append(origin)
        if tone:
            conditions.append("emotional_tone = ?")
            params.append(tone)
        if person:
            conditions.append("LOWER(involves_people) LIKE ?")
            params.append(f"%{person.lower()}%")
        if tag:
            conditions.append("LOWER(tags) LIKE ?")
            params.append(f"%{tag.lower()}%")

        where = "WHERE " + " AND ".join(conditions) if conditions else ""

        # -- Sort --
        sort_map = {
            "recent": "timestamp DESC",
            "oldest": "timestamp ASC",
            "strongest": "memory_strength DESC",
            "recalled": "times_recalled DESC",
        }
        order_by = sort_map.get(sort, "timestamp DESC")

        with _sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()

            # Total count
            cursor.execute(f"SELECT COUNT(*) FROM memories {where}", params)
            total = cursor.fetchone()[0]

            # Paginated rows
            cursor.execute(
                f"SELECT * FROM memories {where} ORDER BY {order_by} LIMIT ? OFFSET ?",
                params + [limit, offset],
            )
            items = [self._row_to_memory(row) for row in cursor.fetchall()]

        return {"items": items, "total": total}

