    def close(self) -> None:
        """
        Explicitly close ChromaDB client and release resources.
        Safe to call multiple times.
        """
        import gc

        if self._closed:
            return

        with self._chroma_lock:
            if hasattr(self, 'chroma_client') and self.chroma_client:
                try:
                    # ChromaDB PersistentClient doesn't have close(),
                    # but we clear references and force garbage collection
                    self.collection = None
                    self.chroma_client = None
                except Exception as e:
                    print(f"Warning: Error closing ChromaDB: {e}")

            # Clear BM25 index to free memory
            with self._bm25_lock:
                self.bm25_index = None
                self.bm25_doc_ids = []
                self.bm25_documents = []

            self._closed = True

        # Force garbage collection to release ChromaDB resources
        gc.collect()

    def __enter__(self) -> 'ExperientialMemorySystem':
        """Support 'with' statement for automatic resource management."""
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> bool:
        """Cleanup on context exit."""
        self.close()
        return False  # Don't suppress exceptions

    def __del__(self) -> None:
        """Destructor - fallback cleanup on garbage collection."""
        try:
            self.close()
        except Exception:
            pass  # Ignore errors during destruction
    
