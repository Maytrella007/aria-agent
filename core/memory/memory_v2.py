    def get_people_distribution(self, limit: Optional[int] = None) -> List[Tuple[str, int]]:
        """
        Count of memories per person involved, derived from the involves_people
        JSON column. Returns a list of (person, count) tuples sorted descending.

        Args:
            limit: optional cap on the number of returned entries (top-N)
        """
        counts: Dict[str, int] = {}
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT involves_people FROM memories")
            for (raw,) in cursor.fetchall():
                if not raw:
                    continue
                try:
                    people = json.loads(raw)
                except (json.JSONDecodeError, TypeError):
                    continue
                if not isinstance(people, list):
                    continue
                for person in people:
                    if not person:
                        continue
                    counts[person] = counts.get(person, 0) + 1

        ranked = sorted(counts.items(), key=lambda kv: kv[1], reverse=True)
        if limit is not None:
            ranked = ranked[:limit]
        return ranked

