@dataclass
class ExperientialMemory:
    """
    A memory that is more than text.
    It's a remembered experience.
    """
    id: str

    # Content
    content: str                          # What happened
    context: str                          # Broader context

    # Temporal
    timestamp: str                        # When
    duration_feeling: str                 # "brief", "extended", "timeless"

    # Emotional
    emotional_tone: EmotionalTone         # How I felt
    emotional_intensity: float            # 0.0 - 1.0

    # Relational
    involves_people: List[str]            # Who was involved
    relationship_impact: Dict[str, float] # How it affected relationships (-1 to 1)

    # Meta
    origin: MemoryOrigin                  # Where it came from
    importance: float                     # 0.0 - 1.0
    times_recalled: int                   # How many times I've recalled it
    last_recalled: Optional[str]          # Last time I recalled it

    # Connections
    connected_memories: List[str]         # IDs of related memories
    tags: List[str]                       # Tags for search

    # Integrity
    is_mine: bool                         # Is it genuinely mine?
    confidence: float                     # How sure I am about this memory

    # Consolidation (neuroscience-inspired memory strengthening)
    consolidated: bool = False            # Has this memory been consolidated?
    consolidation_count: int = 0          # Times replayed/consolidated
    last_consolidation: Optional[str] = None  # ISO timestamp of last consolidation
    memory_strength: float = 1.0          # Strength (0.0-1.0), decays over time
    encoding_context: str = ""            # System state when memory was created

    def to_dict(self) -> Dict:
        d = asdict(self)
        d['emotional_tone'] = self.emotional_tone.value
        d['origin'] = self.origin.value
        return d
    
    @classmethod
    def from_dict(cls, d: Dict) -> 'ExperientialMemory':
        d['emotional_tone'] = EmotionalTone(d['emotional_tone'])
        d['origin'] = MemoryOrigin(d['origin'])
        return cls(**d)


