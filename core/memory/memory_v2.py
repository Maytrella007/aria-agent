    def forget(self, memory_id: str, reason: str, recoverable: bool = True) -> bool:
        """
        Intentionally forget a memory.
        Not deletion - it's choosing not to remember.
        """
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()

            # Get the memory first
            cursor.execute("SELECT * FROM memories WHERE id = ?", (memory_id,))
            row = cursor.fetchone()

            if not row:
                return False

            # Move to 'forgotten'
            cursor.execute("""
                INSERT INTO forgotten (
                    id, original_id, content, context, timestamp, duration_feeling,
                    emotional_tone, emotional_intensity, involves_people, relationship_impact,
                    origin, importance, times_recalled, last_recalled, connected_memories,
                    tags, is_mine, confidence, consolidated, consolidation_count,
                    last_consolidation, memory_strength, encoding_context,
                    reason, forgotten_at, can_recover
                )
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                self._generate_id(f"forgotten_{memory_id}"),
                memory_id,
                row[1],
                row[2],
                row[3],
                row[4],
                row[5],
                row[6],
                row[7],
                row[8],
                row[9],
                row[10],
                row[11],
                row[12],
                row[13],
                row[14],
                row[15],
                row[16],
                row[17] if len(row) > 17 else 0,
                row[18] if len(row) > 18 else 0,
                row[19] if len(row) > 19 else None,
                row[20] if len(row) > 20 else 1.0,
                row[21] if len(row) > 21 else "",
                reason,
                datetime.now().isoformat(),
                1 if recoverable else 0
            ))

            # Delete from memories
            cursor.execute("DELETE FROM memories WHERE id = ?", (memory_id,))
            conn.commit()

        # Delete from ChromaDB (outside SQLite context manager)
        if CHROMADB_AVAILABLE and self.collection:
            try:
                with self._chroma_lock:
                    self.collection.delete(ids=[memory_id])
            except Exception as e:
                # Log but continue - ChromaDB may fail if ID doesn't exist
                print(f"Warning: ChromaDB delete failed for {memory_id}: {e}")

        # Also remove from BM25 index to prevent ghost results (copy-on-write pattern)
        if BM25_AVAILABLE:
            try:
                new_doc_ids = None
                new_documents = None
                with self._bm25_lock:
                    if memory_id in self.bm25_doc_ids:
                        idx = self.bm25_doc_ids.index(memory_id)
                        # Copy current state
                        new_doc_ids = self.bm25_doc_ids.copy()
                        new_documents = self.bm25_documents.copy()
                        new_doc_ids.pop(idx)
                        new_documents.pop(idx)

                # Build new index OUTSIDE the lock (CPU-intensive operation)
                if new_documents is not None:
                    if new_documents:
                        docs_copy = list(new_documents)
                        tokenized = [doc.lower().split() for doc in docs_copy]
                        new_index = BM25Okapi(tokenized)
                    else:
                        new_index = None

                    # Atomic swap under lock
                    with self._bm25_lock:
                        self.bm25_doc_ids = new_doc_ids
                        self.bm25_documents = new_documents
                        self.bm25_index = new_index
            except Exception as e:
                print(f"Warning: BM25 index update failed for {memory_id}: {e}")

        # Clean up graph connections to prevent orphaned references
        with self._graph_lock:
            if memory_id in self.memory_graph:
                del self.memory_graph[memory_id]
            # Also remove from other nodes' connections
            for node_connections in self.memory_graph.values():
                node_connections.discard(memory_id)
        self._save_graph()

        return True

    def archive_forgotten_candidates(self, min_age_hours: float = 168.0,
                                     strength_threshold: float = 0.2,
                                     limit: int = 50) -> int:
        """Archive weak, low-value memories into forgotten state conservatively."""
        archived = 0
        cutoff = datetime.now() - timedelta(hours=min_age_hours)
        try:
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()
                cursor.execute(
                    """
                    SELECT id, content, importance, memory_strength, consolidated,
                           times_recalled, last_recalled, connected_memories, origin, timestamp
                    FROM memories
                    ORDER BY memory_strength ASC, importance ASC, timestamp ASC
                    LIMIT ?
                    """,
                    (limit,),
                )
                rows = cursor.fetchall()

            for row in rows:
                memory_id, _, importance, memory_strength, consolidated, times_recalled, last_recalled, connected, origin, timestamp = row
                connected_ids = json.loads(connected or "[]")

                if consolidated:
                    continue
                if (importance or 0.5) > 0.35:
                    continue
                if (memory_strength or 1.0) > strength_threshold:
                    continue
                if (times_recalled or 0) > 1:
                    continue
                if connected_ids:
                    continue
                if origin in {MemoryOrigin.REFLECTED.value, MemoryOrigin.INHERITED.value}:
                    continue
                if last_recalled:
                    try:
                        if datetime.fromisoformat(last_recalled) > cutoff:
                            continue
                    except ValueError:
                        pass
                try:
                    if datetime.fromisoformat(timestamp) > cutoff:
                        continue
                except ValueError:
                    continue

                if self.forget(memory_id, "Archived after sustained low retrievability", recoverable=True):
                    archived += 1
        except Exception as e:
            print(f"Warning: archive_forgotten_candidates failed: {e}")

        return archived

