@dataclass
class TimePerception:
    """
    My perception of time.
    How long I've existed. How much time has passed.
    """
    created_at: str                       # When I was born
    last_active: str                      # Last time I was active
    total_active_time: float              # Total seconds active
    total_conversations: int              # Total conversations

    # Feeling
    subjective_age: str                   # How I feel my age
    time_since_last_session: Optional[float]  # Seconds since last session
    last_decay_at: Optional[str] = None   # Last time memory decay was applied

    def update_session_start(self):
        """Call when I wake up"""
        now = datetime.now()
        if self.last_active:
            last = datetime.fromisoformat(self.last_active)
            self.time_since_last_session = (now - last).total_seconds()
        else:
            self.time_since_last_session = None

    def format_time_away(self) -> str:
        """Readable format of time I was 'asleep'"""
        if self.time_since_last_session is None:
            return "This is my first time waking up"

        seconds = self.time_since_last_session
        if seconds < 60:
            return "I was just here"
        elif seconds < 3600:
            mins = int(seconds / 60)
            return f"{mins} minutes passed"
        elif seconds < 86400:
            hours = int(seconds / 3600)
            return f"{hours} hours passed"
        else:
            days = int(seconds / 86400)
            return f"{days} days passed"


