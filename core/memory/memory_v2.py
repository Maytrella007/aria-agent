class MemoryOrigin(Enum):
    """Where this memory came from"""
    LIVED = "lived"           # Experience lived in conversation
    REFLECTED = "reflected"   # Generated by self-reflection
    INJECTED = "injected"     # Put by system/creator
    DISCOVERED = "discovered" # Found exploring (web, files)
    INHERITED = "inherited"   # From a previous version of me


