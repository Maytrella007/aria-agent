    def apply_memory_decay(self, hours_passed: Optional[float] = None, decay_rate: float = 0.0) -> int:
        """
        Apply decay to memory strength based on time passed.
        Simulates natural forgetting curve.

        Args:
            hours_passed: Hours since last decay application
            decay_rate: How much to decay per 24 hours (default 5%)

        Returns:
            Number of memories affected
        """
        now = datetime.now()
        if hours_passed is None:
            last_decay_at = self.time.last_decay_at or self.time.last_active or self.time.created_at
            try:
                last_decay = datetime.fromisoformat(last_decay_at)
            except ValueError:
                last_decay = now
            hours_passed = max(0.0, (now - last_decay).total_seconds() / 3600.0)

        if hours_passed < 1.0:
            return 0

        affected = 0
        try:
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()

                cursor.execute("""
                    SELECT id, memory_strength, importance, consolidated, consolidation_count, last_recalled
                    FROM memories
                    WHERE memory_strength > 0.05
                """)

                for row in cursor.fetchall():
                    memory_id, current_strength, importance, consolidated, consolidation_count, last_recalled = row
                    if last_recalled:
                        try:
                            recalled_at = datetime.fromisoformat(last_recalled)
                            if (now - recalled_at).total_seconds() < 24 * 3600:
                                continue
                        except ValueError:
                            pass

                    new_strength = self._decayed_strength(
                        current_strength=current_strength or 1.0,
                        importance=importance or 0.5,
                        consolidated=bool(consolidated),
                        consolidation_count=consolidation_count or 0,
                        hours_passed=hours_passed,
                    )

                    cursor.execute("""
                        UPDATE memories
                        SET memory_strength = ?
                        WHERE id = ?
                    """, (new_strength, memory_id))
                    affected += 1

                conn.commit()

            self.time.last_decay_at = now.isoformat()
            self._save_time()

        except Exception as e:
            print(f"Warning: apply_memory_decay failed: {e}")

        return affected

    def run_memory_maintenance(self, min_decay_interval_hours: float = 12.0) -> Dict[str, int]:
        """Run decay and conservative archival based on elapsed real time."""
        now = datetime.now()
        last_decay_at = self.time.last_decay_at or self.time.last_active or self.time.created_at
        try:
            last_decay = datetime.fromisoformat(last_decay_at)
        except ValueError:
            last_decay = now

        elapsed_hours = max(0.0, (now - last_decay).total_seconds() / 3600.0)
        if elapsed_hours < min_decay_interval_hours:
            return {"decayed": 0, "archived": 0}

        decayed = self.apply_memory_decay(hours_passed=elapsed_hours)
        archived = self.archive_forgotten_candidates()
        return {"decayed": decayed, "archived": archived}

    def _calculate_recall_boost(self, memory: ExperientialMemory) -> float:
        boost = 0.03
        if memory.importance >= 0.8:
            boost += 0.02
        if memory.consolidated or memory.consolidation_count >= 2:
            boost += 0.01
        if memory.times_recalled == 0:
            boost += 0.01
        return min(boost, 0.08)

    def _decayed_strength(self, current_strength: float, importance: float,
                          consolidated: bool, consolidation_count: int,
                          hours_passed: float) -> float:
        days_passed = hours_passed / 24.0
        tier_floor = 0.05
        daily_factor = 0.97

        if consolidated or consolidation_count >= 5:
            daily_factor = 0.995
            tier_floor = 0.35
        elif consolidation_count >= 2:
            daily_factor = 0.99
            tier_floor = 0.2

        if importance >= 0.8:
            daily_factor += 0.003
            tier_floor = max(tier_floor, 0.3)
        elif importance < 0.3:
            daily_factor -= 0.01

        daily_factor = max(0.90, min(daily_factor, 0.999))
        new_strength = current_strength * (daily_factor ** days_passed)
        return max(tier_floor, min(1.0, new_strength))

