        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT INTO memories VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                memory.id,
                memory.content,
                memory.context,
                memory.timestamp,
                memory.duration_feeling,
                memory.emotional_tone.value,
                memory.emotional_intensity,
                json.dumps(memory.involves_people),
                json.dumps(memory.relationship_impact),
                memory.origin.value,
                memory.importance,
                memory.times_recalled,
                memory.last_recalled,
                json.dumps(memory.connected_memories),
                json.dumps(memory.tags),
                1 if memory.is_mine else 0,
                memory.confidence,
                # Consolidation fields (5 new columns)
                1 if memory.consolidated else 0,
                memory.consolidation_count,
                memory.last_consolidation,
                memory.memory_strength,
                memory.encoding_context
            ))
            conn.commit()
        
        # Index for semantic search (IMPROVED - all metadata)
        if CHROMADB_AVAILABLE and self.collection:
            # Create enriched document: content + context + tags for better embedding
            # FIX BUG #3: Include tags in embedding for tag-based semantic search
            enriched_document = content
            if context:
                enriched_document = f"{content}\n\nContext: {context}"
            if tags:
                enriched_document += f"\n\nTags: {', '.join(tags)}"

            # Complete metadata for advanced filtering
            metadata = {
                # Emotional
                "emotional_tone": emotional_tone.value,
                "emotional_intensity": emotional_intensity,

                # Importance and confidence
                "importance": importance,
                "confidence": memory.confidence,

                # Origin and authenticity
                "origin": origin.value,
                "is_mine": 1 if memory.is_mine else 0,

                # Relationships (as comma-separated string for filtering)
                "involves_people": ",".join(involves or []),
                "has_people": 1 if involves else 0,

                # Tags (as comma-separated string; ChromaDB doesn't support $contains
                # for metadata, so tag filtering must be done in Python post-query)
                "tags": ",".join(tags or []),
                "has_tags": 1 if tags else 0,

                # Connections
                "has_connections": 0,  # Updated when connected

                # Temporal
                "timestamp": memory.timestamp,
            }

            try:
                self.collection.upsert(
                    documents=[enriched_document],
                    metadatas=[metadata],
                    ids=[memory.id]
                )
            except Exception as e:
                print(f"Warning: ChromaDB indexing failed for memory {memory.id}: {e}")

            # Update BM25 index
            self._update_bm25_index(memory.id, content, context, tags)

            # Auto-connect with related memories
            self._auto_connect_memories(memory)

        # Update relationships if people are involved (thread-safe)
        if involves:
            with self._relationships_lock:
                for person in involves:
                    if person.lower() in self.relationships:
                        rel = self.relationships[person.lower()]
                        rel.last_contact = memory.timestamp
                        rel.total_interactions += 1
                        rel.shared_experiences.append(memory.id)
            self._save_relationships()
        
        return memory
    
