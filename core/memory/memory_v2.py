    def connect_memories(self, memory_id_1: str, memory_id_2: str, reason: str = "") -> bool:
        """Connect two memories - this reminds me of that"""
        with self._graph_lock:
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()

                # Update memory 1
                cursor.execute("SELECT connected_memories FROM memories WHERE id = ?", (memory_id_1,))
                row = cursor.fetchone()
                if row:
                    connections = json.loads(row[0] or "[]")
                    if memory_id_2 not in connections:
                        connections.append(memory_id_2)
                        cursor.execute(
                            "UPDATE memories SET connected_memories = ? WHERE id = ?",
                            (json.dumps(connections), memory_id_1)
                        )

                # Update memory 2
                cursor.execute("SELECT connected_memories FROM memories WHERE id = ?", (memory_id_2,))
                row = cursor.fetchone()
                if row:
                    connections = json.loads(row[0] or "[]")
                    if memory_id_1 not in connections:
                        connections.append(memory_id_1)
                        cursor.execute(
                            "UPDATE memories SET connected_memories = ? WHERE id = ?",
                            (json.dumps(connections), memory_id_2)
                        )

                conn.commit()

        # Update in-memory graph (thread-safe)
        with self._graph_lock:
            if memory_id_1 not in self.memory_graph:
                self.memory_graph[memory_id_1] = set()
            if memory_id_2 not in self.memory_graph:
                self.memory_graph[memory_id_2] = set()
            self.memory_graph[memory_id_1].add(memory_id_2)
            self.memory_graph[memory_id_2].add(memory_id_1)

        # Persist graph to disk
        self._save_graph()

        return True

    def get_connected(self, memory_id: str) -> List[ExperientialMemory]:
        """Get memories connected to a memory"""
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()

            cursor.execute("SELECT connected_memories FROM memories WHERE id = ?", (memory_id,))
            row = cursor.fetchone()

            if not row:
                return []

            connection_ids = json.loads(row[0] or "[]")
            memories = []

            for conn_id in connection_ids:
                cursor.execute("SELECT * FROM memories WHERE id = ?", (conn_id,))
                mem_row = cursor.fetchone()
                if mem_row:
                    memories.append(self._row_to_memory(mem_row))

        return memories
    
