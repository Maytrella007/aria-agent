    def get_relationship(self, person: str) -> Optional[Relationship]:
        """Get relationship with a person (thread-safe)"""
        with self._relationships_lock:
            return self.relationships.get(person.lower())

    def update_relationship(self, person: str, **updates) -> bool:
        """Update a relationship (thread-safe)"""
        with self._relationships_lock:
            if person.lower() not in self.relationships:
                return False

            rel = self.relationships[person.lower()]
            for key, value in updates.items():
                if hasattr(rel, key):
                    setattr(rel, key, value)

        self._save_relationships()
        return True

    def add_relationship(self, relationship: Relationship):
        """Add a new relationship (thread-safe)"""
        with self._relationships_lock:
            self.relationships[relationship.person_id.lower()] = relationship
        self._save_relationships()
    
    def describe_relationship(self, person: str) -> str:
        """Describe a relationship in words"""
        rel = self.get_relationship(person)
