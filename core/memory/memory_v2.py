    def rebuild_chroma_index(self) -> Dict[str, int]:
        """
        Rebuild ChromaDB index from SQLite database.
        Use this to sync memories that were created without ChromaDB.

        Returns:
            Dict with stats: added, skipped, failed counts
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return {"error": "ChromaDB not available"}

        stats = {"added": 0, "skipped": 0, "failed": 0}

        # Get all memories from SQLite
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM memories")
            rows = cursor.fetchall()

        # Get existing IDs in ChromaDB
        existing_ids = set()
        try:
            result = self.collection.get()
            existing_ids = set(result.get("ids", []))
        except Exception:
            pass

        print(f"Rebuilding ChromaDB index...")
        print(f"  SQLite memories: {len(rows)}")
        print(f"  ChromaDB documents: {len(existing_ids)}")

        for row in rows:
            try:
                memory = self._row_to_memory(row)

                # Skip if already indexed
                if memory.id in existing_ids:
                    stats["skipped"] += 1
                    continue

                # Create enriched document
                enriched_document = memory.content
                if memory.context:
                    enriched_document = f"{memory.content}\n\nContext: {memory.context}"

                # Build metadata
                metadata = {
                    "emotional_tone": memory.emotional_tone.value,
                    "emotional_intensity": memory.emotional_intensity,
                    "importance": memory.importance,
                    "confidence": memory.confidence,
                    "origin": memory.origin.value,
                    "is_mine": 1 if memory.is_mine else 0,
                    "involves_people": ",".join(memory.involves_people),
                    "has_people": 1 if memory.involves_people else 0,
                    "tags": ",".join(memory.tags),
                    "has_tags": 1 if memory.tags else 0,
                    "has_connections": 1 if memory.connected_memories else 0,
                    "timestamp": memory.timestamp,
                }

                # Add to ChromaDB
                self.collection.upsert(
                    documents=[enriched_document],
                    metadatas=[metadata],
                    ids=[memory.id]
                )
                stats["added"] += 1

                # Also update BM25 index
                self._update_bm25_index(memory.id, memory.content, memory.context, memory.tags)

            except Exception as e:
                stats["failed"] += 1
                print(f"  Failed to index {row[0][:12]}...: {e}")

        print(f"  Added: {stats['added']}, Skipped: {stats['skipped']}, Failed: {stats['failed']}")
        return stats

