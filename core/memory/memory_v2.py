    def backup_memories(self, backup_path: str = None) -> str:
        """
        Create a backup of all memories in JSON format.

        Args:
            backup_path: Path to backup file (optional)

        Returns:
            Path to the created backup file
        """
        if backup_path is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            backup_dir = os.path.join(self.data_dir, "backups")
            os.makedirs(backup_dir, exist_ok=True)
            backup_path = os.path.join(backup_dir, f"memories_backup_{timestamp}.json")

        # Load all memories
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM memories")
            rows = cursor.fetchall()

        memories = []
        for row in rows:
            try:
                memory = self._row_to_memory(row)
                memories.append(memory.to_dict())
            except (ValueError, KeyError, TypeError):
                pass

        # Save backup
        backup_data = {
            "timestamp": datetime.now().isoformat(),
            "total_memories": len(memories),
            "memories": memories,
            "relationships": {k: v.to_dict() for k, v in self.relationships.items()},
            "time_perception": asdict(self.time)
        }

        with open(backup_path, 'w', encoding='utf-8') as f:
            json.dump(backup_data, f, indent=2, ensure_ascii=False)

        print(f"Backup created: {backup_path} ({len(memories)} memories)")
        return backup_path

    def restore_from_backup(self, backup_path: str) -> Dict[str, int]:
        """
        Restore memories from a JSON backup.

        Args:
            backup_path: Path to backup file

        Returns:
            Restoration statistics
        """
        if not os.path.exists(backup_path):
            return {"error": f"Backup not found: {backup_path}"}

        with open(backup_path, 'r', encoding='utf-8') as f:
            backup_data = json.load(f)

        stats = {"restored": 0, "failed": 0, "total": len(backup_data.get("memories", []))}

        for memory_dict in backup_data.get("memories", []):
            try:
                # Convert to ExperientialMemory
                memory = ExperientialMemory.from_dict(memory_dict)

                # FIX: Add defaults for missing consolidation fields
                # (for backward compatibility with old backups)
                if not hasattr(memory, 'consolidated') or memory.consolidated is None:
                    memory.consolidated = False
                if not hasattr(memory, 'consolidation_count') or memory.consolidation_count is None:
                    memory.consolidation_count = 0
                if not hasattr(memory, 'last_consolidation'):
                    memory.last_consolidation = None
                if not hasattr(memory, 'memory_strength') or memory.memory_strength is None:
                    memory.memory_strength = 1.0
                if not hasattr(memory, 'encoding_context'):
                    memory.encoding_context = ""

                # Insert into SQLite (22 columns - FIX for schema match)
                with sqlite3.connect(self.db_path) as conn:
                    cursor = conn.cursor()
                    cursor.execute("""
                        INSERT OR REPLACE INTO memories VALUES
                        (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, (
                        memory.id, memory.content, memory.context,
                        memory.timestamp, memory.duration_feeling,
                        memory.emotional_tone.value, memory.emotional_intensity,
                        json.dumps(memory.involves_people),
                        json.dumps(memory.relationship_impact),
                        memory.origin.value, memory.importance,
                        memory.times_recalled, memory.last_recalled,
                        json.dumps(memory.connected_memories),
                        json.dumps(memory.tags),
                        1 if memory.is_mine else 0, memory.confidence,
                        # NEW: 5 consolidation fields
                        1 if memory.consolidated else 0,
                        memory.consolidation_count,
                        memory.last_consolidation,
                        memory.memory_strength,
                        memory.encoding_context
                    ))
                    conn.commit()

                stats["restored"] += 1

            except Exception as e:
                stats["failed"] += 1
                print(f"Warning: Failed to restore memory {memory_dict.get('id', 'unknown')}: {e}")

        # Rebuild indexes
        self.migrate_to_enhanced_chromadb()

        print(f"Restoration completed: {stats['restored']}/{stats['total']}")
        return stats


