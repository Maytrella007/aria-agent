    # =========================================
    
    def recall(
        self,
        query: str,
        limit: int = 5,
        emotion_filter: EmotionalTone = None,
        person_filter: str = None,
        origin_filter: MemoryOrigin = None,
        min_importance: float = None,
        use_hybrid: bool = True,
        alpha: float = 0.7  # Weight for semantic search (0.7 semantic, 0.3 BM25)
    ) -> List[ExperientialMemory]:
        """
        Recall relevant memories (IMPROVED with hybrid search and filters).

        Args:
            query: Text to search for
            limit: Maximum results
            emotion_filter: Filter by emotion
            person_filter: Filter by person involved
            origin_filter: Filter by origin
            min_importance: Minimum importance
            use_hybrid: Use hybrid search (semantic + BM25)
            alpha: Weight for semantic vs BM25 (0.7 = 70% semantic)

        Returns:
            List of memories ordered by relevance
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return self.search_by_text(
                query,
                limit,
                emotion_filter=emotion_filter,
                person_filter=person_filter,
                origin_filter=origin_filter,
                min_importance=min_importance or 0.0,
            )

        # Build filters for ChromaDB
        where_filter = self._build_chroma_filter(
            emotion_filter, person_filter, origin_filter, min_importance
        )

        # Semantic search
        try:
            semantic_results = self.collection.query(
                query_texts=[query],
                n_results=limit * 2,  # Search more for the merge
                where=where_filter if where_filter else None,
                include=["distances"]
            )
        except Exception as e:
            return self.search_by_text(
                query,
                limit,
                emotion_filter=emotion_filter,
                person_filter=person_filter,
                origin_filter=origin_filter,
                min_importance=min_importance or 0.0,
            )

        if not semantic_results['ids'][0]:
            return self.search_by_text(
                query,
                limit,
                emotion_filter=emotion_filter,
                person_filter=person_filter,
                origin_filter=origin_filter,
                min_importance=min_importance or 0.0,
            )

        # If no BM25 or hybrid not wanted, use only semantic
        if not use_hybrid or not BM25_AVAILABLE or self.bm25_index is None:
            memory_ids = semantic_results['ids'][0][:limit]
        else:
            # Hybrid search: combine semantic + BM25
            memory_ids = self._hybrid_search(
                query, semantic_results, limit, alpha
            )

        # Load memories and update times_recalled
        memories = []
        with self._chroma_lock:
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()
                for memory_id in memory_ids:
                    cursor.execute("SELECT * FROM memories WHERE id = ?", (memory_id,))
                    row = cursor.fetchone()
                    if row:
                        memory = self._row_to_memory(row)

                        if emotion_filter and memory.emotional_tone != emotion_filter:
                            continue
                        if origin_filter and memory.origin != origin_filter:
                            continue
                        if min_importance is not None and memory.importance < min_importance:
                            continue

                        # Python post-filter for person (ChromaDB doesn't support $contains)
                        if person_filter:
                            person_lower = person_filter.lower()
                            involves_people = [p.lower() for p in (memory.involves_people or [])]
                            if not any(person_lower in p for p in involves_people):
                                continue  # Skip this memory - person not involved

                        # Update that it was recalled
                        recall_boost = self._calculate_recall_boost(memory)
                        reinforced_strength = min(1.0, memory.memory_strength + recall_boost)
                        cursor.execute("""
                            UPDATE memories
                            SET times_recalled = times_recalled + 1,
                                last_recalled = ?,
                                memory_strength = ?
                            WHERE id = ?
                        """, (datetime.now().isoformat(), reinforced_strength, memory_id))
                        memories.append(memory)

                        # Stop if we have enough after filtering
                        if len(memories) >= limit:
                            break
                conn.commit()

        return memories

    def _build_chroma_filter(
        self,
        emotion: EmotionalTone = None,
        person: str = None,
        origin: MemoryOrigin = None,
        min_importance: float = None
    ) -> Optional[Dict]:
        """Build filter for ChromaDB.

        Note: person filter is NOT applied here because ChromaDB doesn't support
        $contains for metadata. Person filtering is done in Python post-query.
        """
        conditions = []

        if emotion:
            conditions.append({"emotional_tone": emotion.value})

        # NOTE: ChromaDB doesn't support $contains operator for metadata filtering
        # Person filtering is handled in recall() after loading memories
        # if person:
        #     conditions.append({"involves_people": {"$contains": person.lower()}})

        if origin:
            conditions.append({"origin": origin.value})

        if min_importance is not None:
            conditions.append({"importance": {"$gte": min_importance}})

        if not conditions:
            return None

        if len(conditions) == 1:
            return conditions[0]

        return {"$and": conditions}

    def _hybrid_search(
        self,
        query: str,
        semantic_results: Dict,
        limit: int,
        alpha: float
    ) -> List[str]:
        """
        Combine semantic search with BM25 using Reciprocal Rank Fusion.

        Args:
            query: Search text
            semantic_results: Results from ChromaDB
            limit: Number of results
            alpha: Weight for semantic (1-alpha for BM25)

        Returns:
            List of IDs ordered by combined score
        """
        combined_scores = {}
        importance_map = {}

        # Semantic search scores
        for rank, memory_id in enumerate(semantic_results["ids"][0]):
            # Reciprocal Rank: 1/(rank+1)
            combined_scores[memory_id] = alpha * (1 / (rank + 1))
        
        for idx, memory_id in enumerate(semantic_results["ids"][0]):
            if semantic_results.get("metadatas") and semantic_results["metadatas"]:
                metadata = semantic_results["metadatas"][0][idx] or {}
                importance_map[memory_id] = float(metadata.get("importance", 0.5))

        # BM25 scores
        with self._bm25_lock:
            bm25_index = self.bm25_index
            bm25_doc_ids = list(self.bm25_doc_ids)

        if bm25_index and bm25_doc_ids:
            tokenized_query = query.lower().split()
            bm25_scores = bm25_index.get_scores(tokenized_query)

            # Top BM25 results
            if NUMPY_AVAILABLE:
                top_indices = np.argsort(bm25_scores)[::-1][:limit * 2]
            else:
                # Pure-Python fallback when numpy is not available
                indexed_scores = list(enumerate(bm25_scores))
                indexed_scores.sort(key=lambda x: x[1], reverse=True)
                top_indices = [idx for idx, _ in indexed_scores[:limit * 2]]

            for rank, idx in enumerate(top_indices):
                if idx < len(bm25_doc_ids):
                    memory_id = bm25_doc_ids[idx]
                    score = (1 - alpha) * (1 / (rank + 1))

                    if memory_id in combined_scores:
                        combined_scores[memory_id] += score
                    else:
                        combined_scores[memory_id] = score

        if combined_scores:
            placeholders = ",".join("?" for _ in combined_scores)
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()
                cursor.execute(
                    f"SELECT id, importance FROM memories WHERE id IN ({placeholders})",
                    tuple(combined_scores.keys()),
                )
                for memory_id, importance in cursor.fetchall():
                    importance_map[memory_id] = importance if importance is not None else 0.5

            for memory_id in list(combined_scores.keys()):
                importance = importance_map.get(memory_id, 0.5)
                combined_scores[memory_id] *= (0.7 + 0.5 * importance)

        # Sort by combined score
        sorted_ids = sorted(
            combined_scores.keys(),
            key=lambda x: combined_scores[x],
            reverse=True
        )

        return sorted_ids[:limit]
    
