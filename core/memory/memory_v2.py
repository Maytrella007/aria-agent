    def _init_bm25_index(self):
        """Initialize BM25 index for hybrid search"""
        self.bm25_index = None
        self.bm25_doc_ids = []
        self.bm25_documents = []

        if not BM25_AVAILABLE:
            return

        try:
            # Load all memories for BM25
            with sqlite3.connect(self.db_path) as conn:
                cursor = conn.cursor()
                cursor.execute("SELECT id, content, context, tags FROM memories")
                rows = cursor.fetchall()

            if rows:
                self.bm25_doc_ids = [row[0] for row in rows]
                # Combine content + context + tags for BM25
                self.bm25_documents = [
                    f"{row[1]} {row[2] or ''} {' '.join(json.loads(row[3] or '[]'))}"
                    for row in rows
                ]
                tokenized = [doc.lower().split() for doc in self.bm25_documents]
                self.bm25_index = BM25Okapi(tokenized)
        except Exception as e:
            print(f"Warning: BM25 not initialized: {e}")

    def _update_bm25_index(self, memory_id: str, content: str, context: str, tags: List[str]):
        """Update the BM25 index with a new memory (thread-safe with copy-on-write)"""
        if not BM25_AVAILABLE:
            return

        # Build new index OUTSIDE the lock (CPU-intensive operation)
        doc = f"{content} {context or ''} {' '.join(tags or [])}"

        if not doc.strip():
            return

        with self._bm25_lock:
            # Copy current state
            new_doc_ids = self.bm25_doc_ids.copy()
            new_documents = self.bm25_documents.copy()

        # Add new document (outside lock)
        new_doc_ids.append(memory_id)
        new_documents.append(doc)

        # Build new index (CPU-intensive, outside lock)
        tokenized = [d.lower().split() for d in new_documents]
        new_index = BM25Okapi(tokenized)

        # Atomic swap under lock
        with self._bm25_lock:
            self.bm25_doc_ids = new_doc_ids
            self.bm25_documents = new_documents
            self.bm25_index = new_index
    
    def _auto_connect_memories(self, new_memory: 'ExperientialMemory', similarity_threshold: float = 0.3):
        """
        Auto-connect semantically related memories.
        This allows ARIA to navigate between connected memories.
        Thread-safe with ChromaDB lock.
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return

        try:
            # Search for similar memories (protected by lock)
            with self._chroma_lock:
                results = self.collection.query(
                    query_texts=[new_memory.content],
                    n_results=6,  # Search a bit more to filter out itself
                    include=["distances"]
                )

            if not results["ids"][0]:
                return

            connections_made = []
            for i, memory_id in enumerate(results["ids"][0]):
                # Don't connect to itself
                if memory_id == new_memory.id:
                    continue

                # Only connect if distance is below threshold (more similar)
                distance = results["distances"][0][i]
                if distance < similarity_threshold:
                    # Add bidirectional connection
                    self.connect_memories(new_memory.id, memory_id, "auto-connected by similarity")
                    connections_made.append(memory_id)

                    # Maximum 3 automatic connections
                    if len(connections_made) >= 3:
                        break

            # Update has_connections metadata
            if connections_made:
                with self._chroma_lock:
                    self.collection.update(
                        ids=[new_memory.id],
                        metadatas=[{"has_connections": 1}]
                    )

        except Exception as e:
            # Log but don't fail if auto-connection fails
            print(f"Warning: Auto-connection failed: {e}")

    def _auto_connect_all_memories(self, similarity_threshold: float = 0.3) -> int:
        """
        Auto-connect all existing memories.
        Useful for rebuilding connections or connecting old memories.

        Returns:
            Number of connections created
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return 0

        total_connections = 0

        try:
            # Get all memories from ChromaDB
            all_data = self.collection.get(include=["documents", "metadatas"])

            if not all_data["ids"]:
                return 0

            # For each memory, search for similar ones and connect
            for i, memory_id in enumerate(all_data["ids"]):
                content = all_data["documents"][i]

                # Search for similar memories
                results = self.collection.query(
                    query_texts=[content],
                    n_results=5,
                    include=["distances"]
                )

                if not results["ids"][0]:
                    continue

                for j, similar_id in enumerate(results["ids"][0]):
                    # Don't connect to itself
                    if similar_id == memory_id:
                        continue

                    # Only connect if distance is below threshold
                    distance = results["distances"][0][j]
                    if distance < similarity_threshold:
                        # Verify connection doesn't already exist
                        if memory_id in self.memory_graph:
                            if similar_id in self.memory_graph[memory_id]:
                                continue

                        # Add connection
                        self.connect_memories(memory_id, similar_id, "auto-connected")
                        total_connections += 1

        except Exception as e:
            print(f"Warning: Error in auto-connect all memories: {e}")

        return total_connections

    def _save_relationships(self):
        """Save relationships to disk (atomic write, thread-safe)"""
        with self._relationships_lock:
            data = {k: v.to_dict() for k, v in self.relationships.items()}
            # Write INSIDE the lock to prevent race conditions
            atomic_write_yaml(self.relationships_path, data)

    def _save_time(self):
        """Save time perception (atomic write, thread-safe)"""
        with self._time_lock:
            data = asdict(self.time)
            # Write INSIDE the lock to prevent race conditions
            atomic_write_yaml(self.time_path, data)

    def _save_graph(self):
        """Save memory graph to disk (atomic write, thread-safe)"""
        with self._graph_lock:
            # Convert sets to lists for YAML serialization
            data = {k: list(v) for k, v in self.memory_graph.items()}
            atomic_write_yaml(self.graph_path, data)

    def _load_graph(self):
        """Load memory graph from disk"""
        if os.path.exists(self.graph_path):
            with open(self.graph_path, 'r', encoding='utf-8') as f:
                data = yaml.safe_load(f) or {}
            # Convert lists back to sets
            self.memory_graph = {k: set(v) for k, v in data.items()}

    def _generate_id(self, content: str) -> str:
        """Generate unique ID for a memory"""
        unique = f"{content}{datetime.now().isoformat()}"
        return hashlib.sha256(unique.encode()).hexdigest()[:16]
    
