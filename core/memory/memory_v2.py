        """
        Enhanced memory recall with multi-path retrieval.

        Phase 4.1: Combines multiple retrieval strategies:
        1. Semantic search (existing recall method)
        2. Entity-based tag search
        3. Fact store lookup (if available)

        Args:
            query: Text to search for
            limit: Maximum results
            include_facts: Whether to include fact store lookup

        Returns:
            List of memories ordered by relevance (semantic first, then entity-based)
        """
        # Path 1: Semantic search (existing implementation)
        semantic_results = self.recall(query, limit=limit)

        # Path 2: Extract entities from query and search by tags
        entity_results = []
        try:
            from .entity_extractor import extract_entities
            query_entities = extract_entities(query)

            # Search by location tags
            for location in query_entities.locations:
                tag_results = self.search_by_tag(f"location:{location}", limit=3)
                entity_results.extend(tag_results)

            # Search by person tags
            for person in query_entities.people:
                tag_results = self.search_by_tag(f"person:{person}", limit=3)
                entity_results.extend(tag_results)

            # Search by general tags (keywords)
            for tag in query_entities.tags[:5]:  # Limit to first 5 tags
                if not tag.startswith(('location:', 'person:')):
                    tag_results = self.search_by_tag(tag, limit=2)
                    entity_results.extend(tag_results)

        except Exception as e:
            # Don't fail if entity extraction fails
            logger.debug(f"Entity extraction failed: {e}")

        # Path 3: Fact store lookup (if available)
        if include_facts:
            try:
                from .fact_store import FactStore
                fact_db_path = os.path.join(self.data_dir, "facts.db")
                if os.path.exists(fact_db_path):
                    fact_store = FactStore(fact_db_path)
                    related_facts = fact_store.search_by_text(query, limit=5)

                    # Get memories associated with these facts
                    for fact in related_facts:
                        if fact.memory_id:
                            mem = self.get_memory(fact.memory_id)
                            if mem:
                                entity_results.append(mem)
            except Exception:
                pass  # Fact store not available or error

        # Merge and deduplicate results
        seen_ids = set()
        merged = []

        # Prioritize semantic results (they're more contextually relevant)
        for mem in semantic_results:
            if mem.id not in seen_ids:
                seen_ids.add(mem.id)
                merged.append(mem)

        # Add entity results (specific entity matches)
        for mem in entity_results:
            if mem.id not in seen_ids:
                seen_ids.add(mem.id)
                merged.append(mem)

        return merged[:limit]

