    def migrate_to_enhanced_chromadb(self, batch_size: int = 50) -> Dict[str, int]:
        """
        Migrate all existing memories to ChromaDB with complete metadata.
        Useful for updating old memories that only had 3 metadata fields.

        Args:
            batch_size: Number of memories per batch

        Returns:
            Dict with migration statistics
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return {"error": "ChromaDB not available", "migrated": 0}

        stats = {"migrated": 0, "failed": 0, "skipped": 0, "total": 0}

        # Load all memories from SQLite
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM memories")
            rows = cursor.fetchall()

        stats["total"] = len(rows)
        print(f"Migrating {len(rows)} memories to enhanced ChromaDB...")

        # Process in batches
        for i in range(0, len(rows), batch_size):
            batch = rows[i:i+batch_size]

            ids = []
            documents = []
            metadatas = []

            for row in batch:
                try:
                    memory = self._row_to_memory(row)

                    # Enriched document
                    doc = memory.content
                    if memory.context:
                        doc = f"{memory.content}\n\nContext: {memory.context}"

                    # Complete metadata
                    metadata = {
                        "emotional_tone": memory.emotional_tone.value,
                        "emotional_intensity": memory.emotional_intensity,
                        "importance": memory.importance,
                        "confidence": memory.confidence,
                        "origin": memory.origin.value,
                        "is_mine": 1 if memory.is_mine else 0,
                        "involves_people": ",".join(memory.involves_people),
                        "has_people": 1 if memory.involves_people else 0,
                        "tags": ",".join(memory.tags),
                        "has_tags": 1 if memory.tags else 0,
                        "has_connections": 1 if memory.connected_memories else 0,
                        "timestamp": memory.timestamp,
                    }

                    ids.append(memory.id)
                    documents.append(doc)
                    metadatas.append(metadata)

                except Exception as e:
                    stats["failed"] += 1
                    continue

            # Upsert batch
            if ids:
                try:
                    self.collection.upsert(
                        ids=ids,
                        documents=documents,
                        metadatas=metadatas
                    )
                    stats["migrated"] += len(ids)
                except Exception as e:
                    stats["failed"] += len(ids)
                    print(f"Batch error: {e}")

            print(f"  Progress: {min(i+batch_size, len(rows))}/{len(rows)}")

        # Rebuild BM25 index
        self._init_bm25_index()

        print(f"Migration completed: {stats['migrated']}/{stats['total']} memories")
        return stats

    def create_sqlite_indexes(self):
        """
        Create SQLite indexes to improve search performance.
        """
        print("Creating SQLite indexes for better performance...")

        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()

            # Index by timestamp (recent searches)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_timestamp
                ON memories(timestamp DESC)
            """)

            # Index by importance (important searches)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_importance
                ON memories(importance DESC)
            """)

            # Index by emotional tone
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_emotion
                ON memories(emotional_tone)
            """)

            # Index by origin
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_origin
                ON memories(origin)
            """)

            # Index by is_mine (genuine memories)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_mine
                ON memories(is_mine)
            """)

            # Composite index for common searches
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_memories_common
                ON memories(is_mine, importance DESC, timestamp DESC)
            """)

            conn.commit()

        print("Indexes created successfully")

