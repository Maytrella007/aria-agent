    def index_conversation_to_chroma(self, history: list, chunk_size: int = 4):
        """
        Index conversation in ChromaDB using chunking for better search.

        Instead of indexing the entire conversation as a single document,
        it divides it into chunks of N messages (user-ARIA pairs) to maintain
        semantic precision.

        Args:
            history: List of messages
            chunk_size: Number of messages per chunk (default 4 = 2 exchanges)
        """
        if not CHROMADB_AVAILABLE or not self.collection:
            return

        if len(history) < 2:
            return

        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        chunks_added = 0

        # Divide into chunks
        for i in range(0, len(history), chunk_size):
            chunk = history[i:i + chunk_size]

            # Create chunk text
            chunk_text = ""
            for msg in chunk:
                role = "User" if msg.get("role") == "user" else "ARIA"
                content = msg.get('content', '')
                if content:
                    chunk_text += f"{role}: {content}\n\n"

            if not chunk_text.strip():
                continue

            # Unique ID for this chunk
            chunk_id = f"conv_{timestamp}_chunk{i//chunk_size}"

            try:
                self.collection.add(
                    documents=[chunk_text],
                    metadatas=[{
                        "type": "conversation_chunk",
                        "timestamp": datetime.now().isoformat(),
                        "chunk_index": i // chunk_size,
                        "session_id": timestamp
                    }],
                    ids=[chunk_id]
                )
                chunks_added += 1
            except Exception:
                pass

        return chunks_added

